/// `OBJECT_BODIES` as a list in `OBJECT_BODY_IDS` order; ids carry "obj-".
pub fn object_bodies() -> Vec<AvatarDefinition> {
    let starters = examples().into_iter();
    let gallery = GALLERY.iter().map(|(id, name, path, eyes)| definition(id, name, path, *eyes));
    starters
        .chain(gallery)
        .map(|mut one| {
            one.id = format!("obj-{}", one.id);
            one
        })
        .collect()
}
